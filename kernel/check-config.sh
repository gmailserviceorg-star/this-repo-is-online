#!/bin/sh
# fail the build loudly if essential options did not stick (silent drops make unbootable ISOs)
miss=0
for s in BLK_DEV_INITRD RD_ZSTD DEVTMPFS TMPFS SQUASHFS SQUASHFS_ZSTD OVERLAY_FS ISO9660_FS EXT4_FS BLK_DEV_LOOP BLK_DEV_SR BLK_DEV_SD SATA_AHCI \
 USB_XHCI_HCD USB_STORAGE EFI_STUB DRM INET UNIX PROC_FS SYSFS BINFMT_ELF BINFMT_SCRIPT EPOLL SIGNALFD TIMERFD EVENTFD INOTIFY_USER \
 CGROUPS NAMESPACES SECCOMP_FILTER SECURITY_LANDLOCK MODULES TTY VT UNIX98_PTYS; do
 grep -q "^CONFIG_$s=y" "$1" || { echo "MISSING CONFIG_$s=y"; miss=1; }
done
exit $miss
